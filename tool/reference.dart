// Writes the Metacode reference (types, signatures, every widget and its
// props, icons, colors) from the actual sources, so it never drifts.
//
//   dart run tool/reference.dart
//
// Output: .claude/skills/metacode-app/REFERENCE.md (run by tool/check_engine.sh).

import 'dart:io';

import 'package:app_ui/spec.dart';

import 'src/functions.dart' show contextParamTypes;
import 'src/models.dart' show primitives;

const output = '.claude/skills/metacode-app/REFERENCE.md';

void main() {
  final out = StringBuffer()
    ..writeln('# Metacode reference')
    ..writeln()
    ..writeln('<!-- GENERATED by `dart run tool/reference.dart` from '
        'packages/app_ui/lib/spec.dart and tool/src. Do not edit. -->')
    ..writeln()
    ..writeln('Contents: [Files](#files) · [Types](#types) · '
        '[Actions and bindings](#actions-and-bindings) · [ui.yaml](#uiyaml) · '
        '[Widgets](#widgets) · [Icons](#icons) · [Colors](#colors) · '
        '[Text variants](#text-variants) · [Interpreter rules](#interpreter-rules)')
    ..writeln()
    ..writeln('## Files')
    ..writeln()
    ..writeln('All in `metacode/`. Never edit `generated/`.')
    ..writeln()
    ..writeln('| File | Holds |')
    ..writeln('|---|---|')
    ..writeln('| `models.yaml` | Models and enums. The reserved `state` model types state.yaml. |')
    ..writeln('| `state.yaml` | `state:` initial values, validated against the `state` model. |')
    ..writeln('| `ui.yaml` | `widgets:` map of id -> widget. `homePage` is the entry. |')
    ..writeln('| `actions/*.dart` | Functions that return the next state. |')
    ..writeln('| `bindings/*.dart` | Functions that return a value for the UI. |')
    ..writeln('| `test/*_test.dart` | Tests through `app.<function>(...)` (see `test/fixtures.dart`). |')
    ..writeln()
    ..writeln('## Types')
    ..writeln()
    ..writeln('In `models.yaml`:')
    ..writeln()
    ..writeln('| Type | Dart | state.yaml value |')
    ..writeln('|---|---|---|');
  const examples = {
    'string': '`"text"`',
    'boolean': '`true` / `false`',
    'number': '`3`, `2.5`',
    'datetime': '`2026-11-05` or `2026-11-05T10:30:00`',
  };
  primitives.forEach((name, dart) {
    out.writeln('| `$name` | `$dart` | ${examples[name] ?? ''} |');
  });
  out
    ..writeln('| `list(t)` | `List<T>` | a YAML list |')
    ..writeln('| `t?` | `T?` | may be omitted or `null` |')
    ..writeln('| a model name | its class (`task` -> `Task`) | a map of its fields |')
    ..writeln('| an enum name | its enum (`filter` -> `Filter`) | one of its values |')
    ..writeln()
    ..writeln('```yaml')
    ..writeln('task:                 # model -> class Task')
    ..writeln('  title: string')
    ..writeln('  note: string?')
    ..writeln('  tags: list(string)')
    ..writeln('filter: [all, open, done]   # enum -> enum Filter')
    ..writeln('state:                # reserved -> class State')
    ..writeln('  tasks: list(task)')
    ..writeln('  filter: filter')
    ..writeln('```')
    ..writeln()
    ..writeln('Generated classes have mutable fields, a named-parameter constructor '
        '(`Task(title: ..., tags: [...])`) and `copyWith(...)`. Import them with '
        "`import '../generated/state.dart';`.")
    ..writeln()
    ..writeln('## Actions and bindings')
    ..writeln()
    ..writeln('```dart')
    ..writeln('State actionName(State state, [int index], [<type> value])   // returns the next state')
    ..writeln('T bindingName(State state, [int index])                      // returns a value for the UI')
    ..writeln('```')
    ..writeln()
    ..writeln('- The first parameter is always `State`. Others are matched **by name**:');
  contextParamTypes.forEach((name, types) {
    final doc = name == 'index'
        ? 'position of the item inside a `listView`/`gridView` `itemBuilder`'
        : 'the new value from an input (see each widget\'s notes for its type)';
    out.writeln('  - `$name` (${types.join(' | ')}): $doc');
  });
  out
    ..writeln('- Actions get a fresh copy of the state. Change it in place and return it, or return `state.copyWith(...)`.')
    ..writeln('- Bindings return a primitive, a model, an enum, or a `List` of those (nullable allowed).')
    ..writeln('- Names must be unique across all actions and bindings. Private helpers start with `_`.')
    ..writeln()
    ..writeln('## ui.yaml')
    ..writeln()
    ..writeln('```yaml')
    ..writeln('widgets:')
    ..writeln('  homePage:            # entry point')
    ..writeln('    scaffold:')
    ..writeln('      appBar: {title: "Notes"}')
    ..writeln('      body: noteList    # -> the widget with id noteList')
    ..writeln('  noteList:')
    ..writeln('    listView: {data: notes, itemBuilder: noteTile, empty: "No notes"}')
    ..writeln('  noteTile:')
    ..writeln('    listTile: {title: noteTitle, onTap: openNote}   # binding, action')
    ..writeln('```')
    ..writeln()
    ..writeln('- A widget is a map with **one key**, its type: `text: {...}`.')
    ..writeln('- A string node is: a widget id, else a binding (its value is shown as text), else literal text.')
    ..writeln('- Widget ids must not equal a binding or action name.')
    ..writeln('- Some widgets have a shorthand (shown below): `column: [a, b]`, `expanded: child`, `text: "Hi"`.')
    ..writeln('- Widgets with no required props are written with an empty map: `divider: {}`.')
    ..writeln()
    ..writeln('Prop kinds:')
    ..writeln()
    ..writeln('| Kind | Accepts |')
    ..writeln('|---|---|');
  for (final kind in PropKind.values) {
    out.writeln('| `${kind.label}` | ${kind.doc} |');
  }
  out
    ..writeln()
    ..writeln('## Widgets')
    ..writeln();

  final groups = <String, List<String>>{};
  widgetCatalog.forEach((name, spec) {
    (groups[spec.group] ??= []).add(name);
  });
  out.writeln(groups.entries
      .map((g) => '**${g.key}**: ${g.value.map((n) => '`$n`').join(', ')}')
      .join('\n\n'));
  out.writeln();

  for (final group in groups.entries) {
    out
      ..writeln('### ${group.key}')
      ..writeln();
    for (final name in group.value) {
      final spec = widgetCatalog[name]!;
      out
        ..writeln('#### `$name`')
        ..writeln()
        ..writeln(spec.description);
      final shorthand = spec.shorthand.prop;
      if (shorthand != null) {
        final example = switch (spec.shorthand) {
          Shorthand.nodes => '$name: [a, b]',
          Shorthand.node => '$name: child',
          _ => '$name: "Hello"',
        };
        out.writeln('Shorthand: `$example` (sets `$shorthand`).');
      }
      out
        ..writeln()
        ..writeln('| Prop | Kind | Notes |')
        ..writeln('|---|---|---|');
      spec.props.forEach((prop, kind) {
        final kindLabel = kind == PropKind.inline
            ? '${kind.label} (`${spec.inline[prop]}` props)'
            : kind.label;
        out.writeln('| `$prop` | $kindLabel | ${spec.notes[prop] ?? ''} |');
      });
      out.writeln();
    }
  }

  out
    ..writeln('## Icons')
    ..writeln()
    ..writeln(iconNames.map((n) => '`$n`').join(', '))
    ..writeln()
    ..writeln('## Colors')
    ..writeln()
    ..writeln('`#RRGGBB`, `#AARRGGBB`, or a name. Theme names follow the app color scheme:')
    ..writeln()
    ..writeln(colorNames.map((n) => '`$n`').join(', '))
    ..writeln()
    ..writeln('## Text variants')
    ..writeln()
    ..writeln('For `text.style.variant`, from the app theme:')
    ..writeln()
    ..writeln(textVariants.map((n) => '`$n`').join(', '))
    ..writeln()
    ..writeln('## Interpreter rules')
    ..writeln()
    ..writeln('Actions and bindings run in dart_eval. `tool/check.sh` reports violations.')
    ..writeln()
    ..writeln('- Type closure parameters: `tasks.where((Task t) => t.done)`, not `(t) => ...`.')
    ..writeln('- Don\'t interpolate ints from `DateTime` getters (`\'\${d.month}\'`). Use `toIso8601String()`.')
    ..writeln('- Only `dart:` imports and the project\'s own files.')
    ..writeln('- All files are bundled together, so private helper names must be unique across files.');

  File(output).writeAsStringSync(out.toString());
  stdout.writeln('Wrote $output');
}
