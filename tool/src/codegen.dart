import 'functions.dart';
import 'models.dart';

const _header = '// GENERATED by `dart run tool/metacode.dart`. Do not edit.\n';

/// Generates `generated/state.dart`: one class per model, one enum per enum,
/// plus the JSON conversion the engine uses (not meant to be called by hand).
String generateState(Map<String, Model> models) {
  final out = StringBuffer(_header)
    ..writeln('// ignore_for_file: unnecessary_non_null_assertion')
    ..writeln();

  for (final model in models.values) {
    if (model is EnumModel) {
      _writeEnum(out, model);
    } else if (model is ClassModel) {
      _writeClass(out, model, models);
    }
    out.writeln();
  }
  final state = models['state'];
  if (state is ClassModel) _writeDelta(out, state, models);
  return '${out.toString().trimRight()}\n';
}

/// `StateDelta`: the State fields an action changes. Every field is
/// optional; only the ones set are sent, and the engine merges them over the
/// current state (top-level fields, whole values).
void _writeDelta(StringBuffer out, ClassModel state, Map<String, Model> models) {
  final fields = state.fields.entries.toList();
  out
    ..writeln('/// The State fields an action changes. Pass it to `emit`; unset')
    ..writeln('/// fields keep their current value.')
    ..writeln('class StateDelta {');
  if (fields.isEmpty) {
    out.writeln('  StateDelta();');
  } else {
    out.writeln('  StateDelta({');
    for (final f in fields) {
      out.writeln('    this.${f.key},');
    }
    out.writeln('  });');
  }
  out.writeln();
  for (final f in fields) {
    out.writeln('  ${_nullable(dartType(f.value, models))} ${f.key};');
  }
  if (fields.isNotEmpty) out.writeln();
  out
    ..writeln('  Map<String, dynamic> toJson() {')
    ..writeln('    final json = <String, dynamic>{};');
  for (final f in fields) {
    final type = TypeRef(f.value.name, item: f.value.item, optional: false);
    out.writeln("    if (${f.key} != null) json['${f.key}'] = "
        "${_toJson(type, '${f.key}!', models)};");
  }
  out
    ..writeln('    return json;')
    ..writeln('  }')
    ..writeln('}');
}

  /// Generates `generated/core.dart`: what actions receive as `core`
  /// (`core.api`, `core.navigator`) and the routing/ route names. The
  /// calls go to the engine through `package:metacode/engine/host.dart`.
String generateCore(Iterable<String> routes) {
  final out = StringBuffer(_header)
    ..writeln()
    ..writeln("import 'dart:convert';")
    ..writeln()
    ..writeln("import 'package:metacode/engine/host.dart';")
    ..writeln()
    ..writeln('  /// Route names from routing/, for `core.navigator.push`.')
    ..writeln('class Routes {');
  for (final r in routes) {
    out.writeln("  static const String $r = '$r';");
  }
  out
    ..writeln('}')
    ..write(_coreClasses);
  return out.toString();
}

const _coreClasses = r'''

/// What actions can reach besides the state.
class Core {
  Core()
      : api = Api(),
        navigator = AppNavigator();

  /// HTTP requests.
  final Api api;

  /// Opens and closes routing/ routes.
  final AppNavigator navigator;
}

/// An HTTP response. A network error has status 0 and the error as body.
class ApiResponse {
  ApiResponse({required this.status, required this.body});

  final int status;
  final String body;

  bool get ok => status >= 200 && status < 300;

  /// The body parsed as JSON.
  dynamic get json => jsonDecode(body);
}

class Api {
  Future<ApiResponse> get(String url, {Map<String, String>? headers}) =>
      _request('GET', url, null, headers);

  /// [body] is sent as is when it is a String, else JSON-encoded.
  Future<ApiResponse> post(String url,
          {Object? body, Map<String, String>? headers}) =>
      _request('POST', url, body, headers);

  Future<ApiResponse> _request(String method, String url, Object? body,
      Map<String, String>? headers) async {
    final result = await hostCall(
        'api',
        jsonEncode({
          'method': method,
          'url': url,
          'body': body,
          'headers': headers,
        }));
    final json = jsonDecode(result) as Map;
    return ApiResponse(
        status: json['status'] as int, body: json['body'] as String);
  }
}

  /// Pages, bottom sheets and dialogs are all routes (see routing/),
/// so `pop` closes whichever is on top.
class AppNavigator {
  /// Opens [route] (use `Routes`). Completes when it closes.
  Future<void> push(String route) async {
    await hostCall('navigator.push', jsonEncode({'route': route}));
  }

  /// Closes the route on top.
  Future<void> pop() async {
    await hostCall('navigator.pop', '{}');
  }
}
''';

void _writeEnum(StringBuffer out, EnumModel model) {
  final c = model.className;
  out.writeln('enum $c { ${model.values.join(', ')} }');
  out.writeln();
  // dart_eval doesn't support Enum.name / values.byName, so convert explicitly.
  out.writeln('$c \$${model.name}FromJson(String value) {');
  for (final v in model.values.take(model.values.length - 1)) {
    out.writeln("  if (value == '$v') return $c.$v;");
  }
  out.writeln('  return $c.${model.values.last};');
  out.writeln('}');
  out.writeln();
  out.writeln('String \$${model.name}ToJson($c value) {');
  for (final v in model.values.take(model.values.length - 1)) {
    out.writeln("  if (value == $c.$v) return '$v';");
  }
  out.writeln("  return '${model.values.last}';");
  out.writeln('}');
}

void _writeClass(StringBuffer out, ClassModel model, Map<String, Model> models) {
  final c = model.className;
  final fields = model.fields.entries.toList();

  out.writeln('class $c {');
  if (fields.isEmpty) {
    out.writeln('  $c();');
  } else {
    out.writeln('  $c({');
    for (final f in fields) {
      out.writeln('    ${f.value.optional ? '' : 'required '}this.${f.key},');
    }
    out.writeln('  });');
  }
  out.writeln();
  for (final f in fields) {
    out.writeln('  ${dartType(f.value, models)} ${f.key};');
  }
  if (fields.isNotEmpty) out.writeln();

  // copyWith
  if (fields.isEmpty) {
    out.writeln('  $c copyWith() => $c();');
  } else {
    out.writeln('  $c copyWith({');
    for (final f in fields) {
      out.writeln('    ${_nullable(dartType(f.value, models))} ${f.key},');
    }
    out.writeln('  }) {');
    out.writeln('    return $c(');
    for (final f in fields) {
      out.writeln('      ${f.key}: ${f.key} ?? this.${f.key},');
    }
    out.writeln('    );');
    out.writeln('  }');
  }
  out.writeln();

  // fromJson
  out.writeln('  static $c fromJson(Map json) {');
  out.writeln('    return $c(');
  for (final f in fields) {
    out.writeln(
        "      ${f.key}: ${_fromJson(f.value, "json['${f.key}']", models)},");
  }
  out.writeln('    );');
  out.writeln('  }');
  out.writeln();

  // toJson
  out.writeln('  Map<String, dynamic> toJson() {');
  out.writeln('    return {');
  for (final f in fields) {
    out.writeln("      '${f.key}': ${_toJson(f.value, f.key, models)},");
  }
  out.writeln('    };');
  out.writeln('  }');
  out.writeln('}');
}

String _nullable(String type) => type.endsWith('?') ? type : '$type?';

String dartType(TypeRef t, Map<String, Model> models) {
  final base = t.isList
      ? 'List<${dartType(t.item!, models)}>'
      : primitives[t.name] ?? models[t.name]!.className;
  return t.optional ? '$base?' : base;
}

String _fromJson(TypeRef t, String expr, Map<String, Model> models) {
  final String inner;
  if (t.isList) {
    final item = _fromJson(t.item!, 'e', models);
    inner = '($expr as List).map((e) => $item).toList()';
  } else {
    inner = switch (t.name) {
      'string' => '$expr as String',
      'boolean' => '$expr as bool',
      'number' => '$expr as num',
      'datetime' => 'DateTime.parse($expr as String)',
      _ => switch (models[t.name]!) {
          EnumModel m => '\$${m.name}FromJson($expr as String)',
          ClassModel m => '${m.className}.fromJson($expr as Map)',
        },
    };
  }
  return t.optional ? '$expr == null ? null : $inner' : inner;
}

String _toJson(TypeRef t, String expr, Map<String, Model> models) {
  final v = t.optional ? '$expr!' : expr;
  final String inner;
  if (t.isList) {
    final item = _toJson(t.item!, 'e', models);
    inner = item == 'e' ? v : '$v.map((e) => $item).toList()';
  } else {
    inner = switch (t.name) {
      'string' || 'boolean' || 'number' => v,
      'datetime' => '$v.toIso8601String()',
      _ => switch (models[t.name]!) {
          EnumModel m => '\$${m.name}ToJson($v)',
          ClassModel _ => '$v.toJson()',
        },
    };
  }
  if (inner == v) return expr;
  return t.optional ? '$expr == null ? null : $inner' : inner;
}

/// Generates `.generated/labels.dart`: app/views/labels/ as typed getters, for
/// values (and actions) that take `Labels labels`.
String generateLabels(Map<String, String> labels, String? language) {
  final out = StringBuffer(_header)
    ..writeln()
    ..writeln('/// The app\'s text from app/views/labels/${language ?? '<language>'}.yaml.')
    ..writeln('class Labels {')
    ..writeln('  Labels();');
  for (final e in labels.entries) {
    out
      ..writeln()
      ..writeln('  String get ${e.key} => ${_dartString(e.value)};');
  }
  out.writeln('}');
  return out.toString();
}

String _dartString(String value) {
  final escaped = value
      .replaceAll(r'\', r'\\')
      .replaceAll("'", r"\'")
      .replaceAll(r'$', r'\$')
      .replaceAll('\n', r'\n');
  return "'$escaped'";
}

/// Generates `generated/main.dart`: the bridge between the engine and the
/// user's functions. The engine speaks JSON; user code only sees typed objects.
String generateMain(
  List<UserFunction> actions,
  List<UserFunction> bindings,
  List<String> imports,
  Map<String, Model> models,
) {
  final out = StringBuffer(_header)
    ..writeln('// ignore_for_file: non_constant_identifier_names, prefer_function_declarations_over_variables')
    ..writeln()
    ..writeln("import 'dart:convert';")
    ..writeln()
    ..writeln("import 'package:metacode/engine/host.dart';")
    ..writeln();
  if (actions.any((fn) => fn.params.any((p) => p.name == 'core'))) {
    out.writeln("import 'core.dart';");
  }
  if ([...actions, ...bindings]
      .any((fn) => fn.params.any((p) => p.name == 'labels'))) {
    out.writeln("import 'labels.dart';");
  }
  out.writeln("import 'state.dart';");
  for (final i in imports) {
    out.writeln("import '../$i';");
  }
  out.writeln();

  String call(UserFunction fn) {
    final args = [
      'state',
      for (final p in fn.params)
        switch (p.name) {
          'emit' => 'emit',
          'core' => 'Core()',
          'labels' => 'Labels()',
          _ => "params['${p.name}'] as ${p.type}",
        },
    ];
    return '${fn.name}(${args.join(', ')})';
  }

  String paramsLine(UserFunction fn) =>
      fn.params.any((p) => contextParamTypes.containsKey(p.name))
          ? '  final params = jsonDecode(paramsJson) as Map;\n'
          : '';

  for (final fn in actions) {
    out
      ..writeln('Future<String> \$action_${fn.name}(String stateJson, String paramsJson) async {')
      ..writeln('  final state = State.fromJson(jsonDecode(stateJson) as Map);')
      ..write(paramsLine(fn));
    if (fn.params.any((p) => p.name == 'emit')) {
      out
        ..writeln('  final emit = (StateDelta delta) {')
        ..writeln('    hostEmit(jsonEncode(delta.toJson()));')
        ..writeln('  };');
    }
    out
      ..writeln('  await ${call(fn)};')
      ..writeln("  return '';")
      ..writeln('}')
      ..writeln();
  }

  for (final fn in bindings) {
    out
      ..writeln('String \$binding_${fn.name}(String stateJson, String paramsJson) {')
      ..writeln('  final state = State.fromJson(jsonDecode(stateJson) as Map);')
      ..write(paramsLine(fn))
      ..writeln('  final result = ${call(fn)};')
      ..writeln('  return jsonEncode(${_encodeDart(fn.returnType, 'result', models)});')
      ..writeln('}')
      ..writeln();
  }
  return '${out.toString().trimRight()}\n';
}

/// JSON-encodes a value of a Dart type returned by a binding.
String _encodeDart(String type, String expr, Map<String, Model> models) {
  var t = type.trim();
  final optional = t.endsWith('?');
  if (optional) t = t.substring(0, t.length - 1);
  final v = optional ? '$expr!' : expr;

  final String inner;
  final list = RegExp(r'^List<(.+)>$').firstMatch(t);
  if (list != null) {
    final item = _encodeDart(list.group(1)!, 'e', models);
    inner = item == 'e' ? v : '$v.map((e) => $item).toList()';
  } else if (t == 'DateTime') {
    inner = '$v.toIso8601String()';
  } else {
    final model = models.values.where((m) => m.className == t).firstOrNull;
    inner = switch (model) {
      EnumModel m => '\$${m.name}ToJson($v)',
      ClassModel _ => '$v.toJson()',
      null => v,
    };
  }
  if (inner == v) return expr;
  return optional ? '$expr == null ? null : $inner' : inner;
}

/// Generates `generated/test_app.dart`: typed wrappers that run each action
/// and binding through the compiled program (dart_eval), exactly like the
/// engine. Used by the app's test/. [appPath] is the app folder relative to
/// the repo root (`metacode`, `metacode/modules/food`), where tests run from.
String generateTestApp(
  List<UserFunction> actions,
  List<UserFunction> bindings,
  Map<String, Model> models,
  String appPath,
) {
  final out = StringBuffer(_header)
    ..writeln()
    ..writeln("import 'dart:convert';")
    ..writeln("import 'dart:io';")
    ..writeln("import 'dart:typed_data';")
    ..writeln()
    ..writeln("import 'package:metacode/engine/host_plugin.dart';")
    ..writeln("import 'package:metacode/engine/program.dart';")
    ..writeln("import 'package:yaml/yaml.dart';")
    ..writeln()
    ..writeln("import 'core.dart';")
    ..writeln("import 'state.dart';")
    ..writeln()
    ..write(_testAppHead.replaceAll(r'$appPath', appPath))
  ..writeln('  /// The initial state from $appPath/app.yaml.')
  ..writeln('  State get initialState {')
  ..writeln("    final doc = loadYaml(File('$appPath/app.yaml').readAsStringSync()) as Map;")
  ..writeln("    final state = Map<String, dynamic>.from(jsonDecode(jsonEncode(doc['state'])) as Map);")
  ..writeln('    return State.fromJson(state);')
  ..writeln('  }');

  String signature(UserFunction fn) => [
        'State state',
        for (final p in fn.params)
          if (contextParamTypes.containsKey(p.name)) '${p.type} ${p.name}',
      ].join(', ');
  String params(UserFunction fn) {
    final context =
        fn.params.where((p) => contextParamTypes.containsKey(p.name));
    return context.isEmpty
        ? ''
        : ', {${context.map((p) => "'${p.name}': ${p.name}").join(', ')}}';
  }

  for (final fn in actions) {
    final contextOnly =
        fn.params.where((p) => contextParamTypes.containsKey(p.name)).toList();
    final sig = ['State state', for (final p in contextOnly) '${p.type} ${p.name}'].join(', ');
    final args = contextOnly.isEmpty
        ? ''
        : ', {${contextOnly.map((p) => "'${p.name}': ${p.name}").join(', ')}}';
    out
      ..writeln()
      ..writeln('  /// Runs `${fn.name}` and returns the state with its deltas applied.')
      ..writeln('  Future<State> ${fn.name}($sig) =>')
      ..writeln("      _run('${fn.name}', state$args);");
  }
  for (final fn in bindings) {
    final raw = "_program.binding('${fn.name}', state.toJson()${params(fn)})";
    out
      ..writeln()
      ..writeln('  ${fn.returnType} ${fn.name}(${signature(fn)}) {')
      ..writeln('    final result = $raw;')
      ..writeln('    return ${_decodeDart(fn.returnType, 'result', models)};')
      ..writeln('  }');
  }
  out.writeln('}');
  return out.toString();
}

const _testAppHead = r'''
  /// Runs actions and bindings through the compiled program, like the engine
  /// does, with typed inputs and outputs. Actions run against a fake host:
  /// deltas are applied to the returned state, navigator calls are recorded
  /// in [navigation] and api requests are answered by [api].
  class TestApp implements MetacodeHost {
    late final MetacodeProgram _program = MetacodeProgram(
      ByteData.sublistView(File('$appPath/.generated/program.evc').readAsBytesSync()),
      jsonDecode(File('$appPath/.generated/manifest.json').readAsStringSync())
          as Map<String, dynamic>,
    )..host = this;

  /// Answers `core.api` requests. Defaults to 404.
  ApiResponse Function(String method, String url, Object? body) api =
      (method, url, body) => ApiResponse(status: 404, body: '');

  /// Every delta the last action emitted, in order (as JSON).
  final emitted = <Map<String, dynamic>>[];

  /// Navigator calls of the last action: `push <route>`, `pop`.
  final navigation = <String>[];

  /// Api requests of the last action: `GET <url>`, `POST <url>`.
  final requests = <String>[];

  Map<String, dynamic> _state = {};

  Future<State> _run(String name, State state,
      [Map<String, dynamic> params = const {}]) async {
    emitted.clear();
    navigation.clear();
    requests.clear();
    _state = jsonDecode(jsonEncode(state.toJson())) as Map<String, dynamic>;
    await _program.action(name, _state, params);
    return State.fromJson(_state);
  }

  @override
  void emit(Map<String, dynamic> delta) {
    emitted.add(delta);
    _state = {..._state, ...delta};
  }

  @override
  Future<Object?> call(String op, Map<String, dynamic> args) async {
    switch (op) {
      case 'api':
        requests.add('${args['method']} ${args['url']}');
        final r = api(args['method'] as String, args['url'] as String, args['body']);
        return {'status': r.status, 'body': r.body};
      case 'navigator.push':
        navigation.add('push ${args['route']}');
      case 'navigator.pop':
        navigation.add('pop');
    }
    return null;
  }

''';

/// Decodes a JSON value back into the Dart type a binding returned.
String _decodeDart(String type, String expr, Map<String, Model> models) {
  var t = type.trim();
  final optional = t.endsWith('?');
  if (optional) t = t.substring(0, t.length - 1);

  final String inner;
  final list = RegExp(r'^List<(.+)>$').firstMatch(t);
  if (list != null) {
    inner = '($expr as List).map((e) => ${_decodeDart(list.group(1)!, 'e', models)}).toList()';
  } else {
    final model = models.values.where((m) => m.className == t).firstOrNull;
    inner = switch ((t, model)) {
      ('DateTime', _) => 'DateTime.parse($expr as String)',
      ('int', _) => '($expr as num).toInt()',
      ('double', _) => '($expr as num).toDouble()',
      (_, EnumModel m) => '\$${m.name}FromJson($expr as String)',
      (_, ClassModel m) => '${m.className}.fromJson($expr as Map)',
      _ => '$expr as $t',
    };
  }
  return optional ? '$expr == null ? null : $inner' : inner;
}
