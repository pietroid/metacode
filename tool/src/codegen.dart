import 'functions.dart';
import 'models.dart';

const _header = '// GENERATED by `dart run tool/metacode.dart`. Do not edit.\n';

/// Generates `generated/state.dart`: one class per model, one enum per enum,
/// plus the JSON conversion the engine uses (not meant to be called by hand).
String generateState(Map<String, Model> models) {
  final out = StringBuffer(_header)
    ..writeln('// ignore_for_file: unnecessary_non_null_assertion')
    ..writeln();

  for (final model in models.values) {
    if (model is EnumModel) {
      _writeEnum(out, model);
    } else if (model is ClassModel) {
      _writeClass(out, model, models);
    }
    out.writeln();
  }
  return '${out.toString().trimRight()}\n';
}

void _writeEnum(StringBuffer out, EnumModel model) {
  final c = model.className;
  out.writeln('enum $c { ${model.values.join(', ')} }');
  out.writeln();
  // dart_eval doesn't support Enum.name / values.byName, so convert explicitly.
  out.writeln('$c \$${model.name}FromJson(String value) {');
  for (final v in model.values.take(model.values.length - 1)) {
    out.writeln("  if (value == '$v') return $c.$v;");
  }
  out.writeln('  return $c.${model.values.last};');
  out.writeln('}');
  out.writeln();
  out.writeln('String \$${model.name}ToJson($c value) {');
  for (final v in model.values.take(model.values.length - 1)) {
    out.writeln("  if (value == $c.$v) return '$v';");
  }
  out.writeln("  return '${model.values.last}';");
  out.writeln('}');
}

void _writeClass(StringBuffer out, ClassModel model, Map<String, Model> models) {
  final c = model.className;
  final fields = model.fields.entries.toList();

  out.writeln('class $c {');
  if (fields.isEmpty) {
    out.writeln('  $c();');
  } else {
    out.writeln('  $c({');
    for (final f in fields) {
      out.writeln('    ${f.value.optional ? '' : 'required '}this.${f.key},');
    }
    out.writeln('  });');
  }
  out.writeln();
  for (final f in fields) {
    out.writeln('  ${dartType(f.value, models)} ${f.key};');
  }
  if (fields.isNotEmpty) out.writeln();

  // copyWith
  if (fields.isEmpty) {
    out.writeln('  $c copyWith() => $c();');
  } else {
    out.writeln('  $c copyWith({');
    for (final f in fields) {
      out.writeln('    ${_nullable(dartType(f.value, models))} ${f.key},');
    }
    out.writeln('  }) {');
    out.writeln('    return $c(');
    for (final f in fields) {
      out.writeln('      ${f.key}: ${f.key} ?? this.${f.key},');
    }
    out.writeln('    );');
    out.writeln('  }');
  }
  out.writeln();

  // fromJson
  out.writeln('  static $c fromJson(Map json) {');
  out.writeln('    return $c(');
  for (final f in fields) {
    out.writeln(
        "      ${f.key}: ${_fromJson(f.value, "json['${f.key}']", models)},");
  }
  out.writeln('    );');
  out.writeln('  }');
  out.writeln();

  // toJson
  out.writeln('  Map<String, dynamic> toJson() {');
  out.writeln('    return {');
  for (final f in fields) {
    out.writeln("      '${f.key}': ${_toJson(f.value, f.key, models)},");
  }
  out.writeln('    };');
  out.writeln('  }');
  out.writeln('}');
}

String _nullable(String type) => type.endsWith('?') ? type : '$type?';

String dartType(TypeRef t, Map<String, Model> models) {
  final base = t.isList
      ? 'List<${dartType(t.item!, models)}>'
      : primitives[t.name] ?? models[t.name]!.className;
  return t.optional ? '$base?' : base;
}

String _fromJson(TypeRef t, String expr, Map<String, Model> models) {
  final String inner;
  if (t.isList) {
    final item = _fromJson(t.item!, 'e', models);
    inner = '($expr as List).map((e) => $item).toList()';
  } else {
    inner = switch (t.name) {
      'string' => '$expr as String',
      'boolean' => '$expr as bool',
      'number' => '$expr as num',
      'datetime' => 'DateTime.parse($expr as String)',
      _ => switch (models[t.name]!) {
          EnumModel m => '\$${m.name}FromJson($expr as String)',
          ClassModel m => '${m.className}.fromJson($expr as Map)',
        },
    };
  }
  return t.optional ? '$expr == null ? null : $inner' : inner;
}

String _toJson(TypeRef t, String expr, Map<String, Model> models) {
  final v = t.optional ? '$expr!' : expr;
  final String inner;
  if (t.isList) {
    final item = _toJson(t.item!, 'e', models);
    inner = item == 'e' ? v : '$v.map((e) => $item).toList()';
  } else {
    inner = switch (t.name) {
      'string' || 'boolean' || 'number' => v,
      'datetime' => '$v.toIso8601String()',
      _ => switch (models[t.name]!) {
          EnumModel m => '\$${m.name}ToJson($v)',
          ClassModel _ => '$v.toJson()',
        },
    };
  }
  if (inner == v) return expr;
  return t.optional ? '$expr == null ? null : $inner' : inner;
}

/// Generates `generated/main.dart`: the bridge between the engine and the
/// user's functions. The engine speaks JSON; user code only sees typed objects.
String generateMain(
  List<UserFunction> actions,
  List<UserFunction> bindings,
  List<String> imports,
  Map<String, Model> models,
) {
  final out = StringBuffer(_header)
    ..writeln('// ignore_for_file: non_constant_identifier_names')
    ..writeln()
    ..writeln("import 'dart:convert';")
    ..writeln()
    ..writeln("import 'state.dart';");
  for (final i in imports) {
    out.writeln("import '../$i';");
  }
  out.writeln();

  String call(UserFunction fn) {
    final args = [
      'state',
      for (final p in fn.params) "params['${p.name}'] as ${p.type}",
    ];
    return '${fn.name}(${args.join(', ')})';
  }

  String paramsLine(UserFunction fn) => fn.params.isEmpty
      ? ''
      : '  final params = jsonDecode(paramsJson) as Map;\n';

  for (final fn in actions) {
    out
      ..writeln('String \$action_${fn.name}(String stateJson, String paramsJson) {')
      ..writeln('  final state = State.fromJson(jsonDecode(stateJson) as Map);')
      ..write(paramsLine(fn))
      ..writeln('  return jsonEncode(${call(fn)}.toJson());')
      ..writeln('}')
      ..writeln();
  }

  for (final fn in bindings) {
    out
      ..writeln('String \$binding_${fn.name}(String stateJson, String paramsJson) {')
      ..writeln('  final state = State.fromJson(jsonDecode(stateJson) as Map);')
      ..write(paramsLine(fn))
      ..writeln('  final result = ${call(fn)};')
      ..writeln('  return jsonEncode(${_encodeDart(fn.returnType, 'result', models)});')
      ..writeln('}')
      ..writeln();
  }
  return '${out.toString().trimRight()}\n';
}

/// JSON-encodes a value of a Dart type returned by a binding.
String _encodeDart(String type, String expr, Map<String, Model> models) {
  var t = type.trim();
  final optional = t.endsWith('?');
  if (optional) t = t.substring(0, t.length - 1);
  final v = optional ? '$expr!' : expr;

  final String inner;
  final list = RegExp(r'^List<(.+)>$').firstMatch(t);
  if (list != null) {
    final item = _encodeDart(list.group(1)!, 'e', models);
    inner = item == 'e' ? v : '$v.map((e) => $item).toList()';
  } else if (t == 'DateTime') {
    inner = '$v.toIso8601String()';
  } else {
    final model = models.values.where((m) => m.className == t).firstOrNull;
    inner = switch (model) {
      EnumModel m => '\$${m.name}ToJson($v)',
      ClassModel _ => '$v.toJson()',
      null => v,
    };
  }
  if (inner == v) return expr;
  return optional ? '$expr == null ? null : $inner' : inner;
}

/// Generates `generated/test_app.dart`: typed wrappers that run each action
/// and binding through the compiled program (dart_eval), exactly like the
/// engine. Used by metacode/test/.
String generateTestApp(
  List<UserFunction> actions,
  List<UserFunction> bindings,
  Map<String, Model> models,
) {
  final out = StringBuffer(_header)
    ..writeln()
    ..writeln("import 'dart:convert';")
    ..writeln("import 'dart:io';")
    ..writeln("import 'dart:typed_data';")
    ..writeln()
    ..writeln("import 'package:metacode/engine/program.dart';")
    ..writeln("import 'package:yaml/yaml.dart';")
    ..writeln()
    ..writeln("import 'state.dart';")
    ..writeln()
    ..writeln('/// Runs actions and bindings through the compiled program, like the')
    ..writeln('/// engine does, with typed inputs and outputs.')
    ..writeln('class TestApp {')
    ..writeln('  final MetacodeProgram _program = MetacodeProgram(')
    ..writeln("    ByteData.sublistView(File('metacode/generated/program.evc').readAsBytesSync()),")
    ..writeln("    jsonDecode(File('metacode/generated/manifest.json').readAsStringSync())")
    ..writeln('        as Map<String, dynamic>,')
    ..writeln('  );')
    ..writeln()
    ..writeln('  /// The state in metacode/state.yaml.')
    ..writeln('  State get initialState {')
    ..writeln("    final doc = loadYaml(File('metacode/state.yaml').readAsStringSync());")
    ..writeln("    return State.fromJson(jsonDecode(jsonEncode(doc['state'])) as Map);")
    ..writeln('  }');

  String signature(UserFunction fn) =>
      ['State state', for (final p in fn.params) '${p.type} ${p.name}'].join(', ');
  String params(UserFunction fn) => fn.params.isEmpty
      ? ''
      : ', {${fn.params.map((p) => "'${p.name}': ${p.name}").join(', ')}}';

  for (final fn in actions) {
    out
      ..writeln()
      ..writeln('  State ${fn.name}(${signature(fn)}) => State.fromJson(')
      ..writeln("      _program.action('${fn.name}', state.toJson()${params(fn)}));");
  }
  for (final fn in bindings) {
    final raw = "_program.binding('${fn.name}', state.toJson()${params(fn)})";
    out
      ..writeln()
      ..writeln('  ${fn.returnType} ${fn.name}(${signature(fn)}) {')
      ..writeln('    final result = $raw;')
      ..writeln('    return ${_decodeDart(fn.returnType, 'result', models)};')
      ..writeln('  }');
  }
  out.writeln('}');
  return out.toString();
}

/// Decodes a JSON value back into the Dart type a binding returned.
String _decodeDart(String type, String expr, Map<String, Model> models) {
  var t = type.trim();
  final optional = t.endsWith('?');
  if (optional) t = t.substring(0, t.length - 1);

  final String inner;
  final list = RegExp(r'^List<(.+)>$').firstMatch(t);
  if (list != null) {
    inner = '($expr as List).map((e) => ${_decodeDart(list.group(1)!, 'e', models)}).toList()';
  } else {
    final model = models.values.where((m) => m.className == t).firstOrNull;
    inner = switch ((t, model)) {
      ('DateTime', _) => 'DateTime.parse($expr as String)',
      ('int', _) => '($expr as num).toInt()',
      ('double', _) => '($expr as num).toDouble()',
      (_, EnumModel m) => '\$${m.name}FromJson($expr as String)',
      (_, ClassModel m) => '${m.className}.fromJson($expr as Map)',
      _ => '$expr as $t',
    };
  }
  return optional ? '$expr == null ? null : $inner' : inner;
}
