// Writes `.generated/INDEX.md` for each app: a map of the app that an agent
// (or a person) reads first, so it opens only the files a change needs.
//
// It lists the state, models, routes, every page and component, action and
// value, shared helper and test state, each with its header comment (the first comment of its file), what
// it uses and what uses it. Everything comes from data the tool already
// validated: WidgetRefs (lib/compiler/ui.dart) and UserFunction touches
// (lib/compiler/functions.dart). Names map to files by convention, so the index
// names things, not paths.

import 'dart:convert';

import 'functions.dart';
import 'issues.dart';
import 'models.dart';
import 'project.dart';

String generateIndex(AppProject app) {
  final out = StringBuffer();
  void line([String s = '']) => out.writeln(s);
  String list(Iterable<String> names) => (names.toList()..sort()).join(', ');

  final pages = {
    for (final e in app.widgetFiles.entries)
      if (e.value.startsWith('app/views/pages/')) e.key,
  };
  final components = app.widgetFiles.keys.toSet().difference(pages);
  final allUsedLabels = <String>{};

  // Reverse references: name -> pages/components (or routes) that use it.
  final usedBy = <String, Set<String>>{};
  void use(String name, String by) => usedBy.putIfAbsent(name, () => {}).add(by);
  for (final MapEntry(key: id, value: r) in app.widgetRefs.entries) {
    for (final n in [...r.widgets, ...r.values, ...r.actions, ...r.modules]) {
      use(n, id);
    }
    allUsedLabels.addAll(r.labels);
  }
  for (final route in app.navigation.routes.values) {
    use(route.widget, 'route ${route.name}');
  }
  final functions = [...app.actions, ...app.bindings];
  final sharedNames = {for (final fn in app.shared) fn.name};
  for (final fn in [...functions, ...app.shared]) {
    allUsedLabels.addAll(fn.labels);
    for (final c in fn.calls) {
      if (sharedNames.contains(c) && c != fn.name) use(c, fn.name);
    }
  }

  line('# ${app.label}: index');
  line();
  line('<!-- Generated by tool/metacode.dart from the code and each file\'s '
      'header comment. Never edit; fix the header comment instead. -->');
  line();
  final appDoc = app.docs['app.yaml'] ?? app.description;
  if (appDoc.isNotEmpty) line(appDoc);
  line();
  line('Folder: `${app.path}/`. Files are named after what they hold: page '
      '`MainPage` is app/views/pages/main_page.yaml, component `Hero` '
      'app/views/components/hero.yaml, action `joinWaitlist` '
      'app/actions/join_waitlist.dart, value `exampleTag` '
      'app/views/values/example_tag.dart, model `food` app/models/food.yaml. '
      'Labels are in app/views/labels/${app.defaultLanguage ?? 'en'}.yaml, '
      'initial state in app.yaml.');

  // State.
  final stateModel = app.models[stateModelName];
  if (stateModel is ClassModel) {
    line();
    line('## State');
    line();
    line('`field: type = initial`, then who writes (w) and reads (r) it.');
    line();
    for (final MapEntry(key: field, value: type)
        in stateModel.fields.entries) {
      final writers = [
        for (final fn in app.actions)
          if (fn.writes.contains(field)) fn.name,
        for (final fn in app.remoteActions)
          if (fn.writes.contains(field)) 'remote ${fn.name}',
      ];
      final readers = [
        for (final fn in functions)
          if (fn.reads.contains(field)) fn.name,
      ];
      final parts = [
        if (writers.isNotEmpty) 'w: ${list(writers)}',
        if (readers.isNotEmpty) 'r: ${list(readers)}',
      ];
      final scope = app.scopes[field];
      line('- $field: $type = ${_initial(app.state[field])}'
          '${scope == null || scope == 'local' ? '' : ' ($scope)'}'
          '${parts.isEmpty ? '' : ' · ${parts.join(' · ')}'}');
    }
  }

  // Other models.
  final models = app.models.values.where((m) => m.name != stateModelName);
  if (models.isNotEmpty) {
    line();
    line('## Models');
    line();
    for (final m in models) {
      final shape = switch (m) {
        ClassModel(:final fields) =>
          '{${[for (final e in fields.entries) '${e.key}: ${e.value}'].join(', ')}}',
        EnumModel(:final values) => 'enum ${values.join(' | ')}',
      };
      final doc = app.docs['app/models/${snakeCase(m.name)}.yaml'] ?? '';
      line('- **${m.name}** $shape${doc.isEmpty ? '' : '. $doc'}');
    }
  }

  // Routes.
  line();
  line('## Routes');
  line();
  for (final r in app.navigation.routes.values) {
    final initial = r.name == app.navigation.initial ? ' (initial)' : '';
    line('- ${r.name}$initial: ${r.type.name} ${r.widget}');
  }

  void widgets(String title, Iterable<String> ids) {
    if (ids.isEmpty) return;
    line();
    line('## $title');
    line();
    for (final id in ids.toList()..sort()) {
      final r = app.widgetRefs[id];
      final doc = app.docs[app.widgetFiles[id]] ?? '';
      line('- **$id**${doc.isEmpty ? '' : ': $doc'}');
      final parts = [
        if (r != null && r.params.isNotEmpty)
          'params: ${[
            for (final e in r.params.entries)
              '.${e.key} (${e.value.map((k) => k.label).join('/')})',
          ].join(', ')}',
        if (r != null && r.widgets.isNotEmpty) 'widgets: ${list(r.widgets)}',
        if (r != null && r.modules.isNotEmpty) 'modules: ${list(r.modules)}',
        if (r != null && r.values.isNotEmpty) 'values: ${list(r.values)}',
        if (r != null && r.actions.isNotEmpty) 'actions: ${list(r.actions)}',
        if (r != null && r.labels.isNotEmpty) 'labels: ${list(r.labels)}',
        if (usedBy[id] != null) 'used by: ${list(usedBy[id]!)}',
      ];
      if (parts.isNotEmpty) line('  ${parts.join(' · ')}');
    }
  }

  widgets('Pages', pages);
  widgets('Components', components);

  void fns(String title, List<UserFunction> list_, bool isAction,
      {bool shared = false}) {
    if (list_.isEmpty) return;
    line();
    line('## $title');
    line();
    for (final fn in [...list_]..sort((a, b) => a.name.compareTo(b.name))) {
      final params = shared
          ? fn.params.map((p) => '${p.type} ${p.name}').join(', ')
          : fn.params.map((p) => p.name).join(', ');
      final sig = isAction
          ? '${fn.name}($params)'
          : '${fn.name}($params) → ${fn.returnType}';
      final calls = fn.calls.where(sharedNames.contains).where((c) => c != fn.name);
      line('- **$sig**${fn.doc.isEmpty ? '' : ': ${fn.doc}'}');
      final parts = [
        if (fn.reads.isNotEmpty) 'reads: ${list(fn.reads)}',
        if (fn.writes.isNotEmpty) 'writes: ${list(fn.writes)}',
        if (fn.routes.isNotEmpty) 'routes: ${list(fn.routes)}',
        if (fn.usesApi) 'api',
        if (fn.labels.isNotEmpty) 'labels: ${list(fn.labels)}',
        if (calls.isNotEmpty) 'shared: ${list(calls)}',
        if (shared) 'in ${fn.file}',
        if (usedBy[fn.name] != null) 'used by: ${list(usedBy[fn.name]!)}',
      ];
      if (parts.isNotEmpty) line('  ${parts.join(' · ')}');
    }
  }

  fns('Actions', app.actions, true);
  fns('Remote actions (app/actions/remote/, on the backend)',
      app.remoteActions, true);
  fns('Values', app.bindings, false);
  fns('Shared', app.shared, false, shared: true);

  if (app.testStates.isNotEmpty) {
    line();
    line('## Test states');
    line();
    line('tests/: selected states the layout check renders at every size.');
    line();
    for (final MapEntry(key: name, value: t) in app.testStates.entries) {
      final doc = app.docs['tests/${snakeCase(name)}.yaml'] ?? '';
      final fields = (t['state'] as Map).keys.join(', ');
      final route = t['route'] == null ? '' : ' · route ${t['route']}';
      line('- **$name**${doc.isEmpty ? '' : ': $doc'}  ');
      line('  sets: $fields$route');
    }
  }

  if (app.modules.isNotEmpty) {
    line();
    line('## Modules');
    line();
    line('Each has its own state, actions and values, and its own index at '
        '`modules/<name>/.generated/INDEX.md`.');
    line();
    for (final m in app.modules.values) {
      final doc = m.docs['app.yaml'] ?? m.description;
      final by = usedBy[m.name];
      line('- **${m.name}**: $doc${by == null ? '' : ' Used by: ${list(by)}.'}');
    }
  }

  // Things nothing references: candidates for cleanup, or a missing link.
  final unused = [
    for (final id in components)
      if (usedBy[id] == null) id,
    for (final fn in [...functions, ...app.shared])
      if (usedBy[fn.name] == null) fn.name,
    for (final key in app.defaultLabels.keys)
      if (!allUsedLabels.contains(key)) key,
  ];
  if (unused.isNotEmpty) {
    line();
    line('## Not referenced from views');
    line();
    line(list(unused));
  }
  return out.toString();
}

/// An initial state value, short: lists as their length.
String _initial(dynamic v) {
  if (v == null) return '—';
  if (v is List) return '[${v.length} items]';
  if (v is Map) return '{…}';
  var s = v is String ? jsonEncode(v) : '$v';
  if (s.length > 40) s = '${s.substring(0, 37)}…"';
  return s;
}

