import 'functions.dart';
import 'models.dart';

const _header = '// GENERATED by `dart run tool/metacode.dart`. Do not edit.\n';

/// Generates `generated/state.dart`: one class per model, one enum per enum,
/// plus the JSON conversion the engine uses (not meant to be called by hand).
///
/// [models]' `state` is the State this side sees (the client's or the
/// backend's, see `stateModelsFor`); [deltaFields], when set, are the
/// fields `StateDelta` has (the client can't emit `shared`).
String generateState(Map<String, Model> models, {List<String>? deltaFields}) {
  final out = StringBuffer(_header)
    ..writeln('// ignore_for_file: unnecessary_non_null_assertion')
    ..writeln();

  for (final model in models.values) {
    if (model is EnumModel) {
      _writeEnum(out, model);
    } else if (model is ClassModel) {
      _writeClass(out, model, models);
    }
    out.writeln();
  }
  final state = models['state'];
  if (state is ClassModel) {
    _writeDelta(
        out,
        deltaFields == null
            ? state
            : ClassModel(state.name, {
                for (final e in state.fields.entries)
                  if (deltaFields.contains(e.key)) e.key: e.value,
              }),
        models);
  }
  out
    ..writeln()
    ..write(_remoteErrorClass)
    ..writeln()
    ..write(_animatedClass);
  return '${out.toString().trimRight()}\n';
}

/// `@Animated()` on a value: when its result changes, whatever it feeds
/// (a color, a number) eases to the new one. Read by the tool
/// (functions.dart), never at runtime.
const _animatedClass = '''
/// Marks a value as animated: when its result changes, the props it feeds
/// ease from the old result to the new one (colors and numbers; anything
/// else switches at once). [ms] is the duration, [curve] one of the curve
/// names in REFERENCE.md; [reverseMs], when set, is the duration when a
/// number goes down (0: at once, e.g. text clearing before it types again).
class Animated {
  final int ms;
  final String curve;
  final int? reverseMs;
  const Animated({this.ms = 220, this.curve = 'easeOut', this.reverseMs});
}
''';

/// Thrown by a remote action to refuse (`throw RemoteError('invalidEmail')`)
/// and by `remote.<name>()` in the local action that called it.
const _remoteErrorClass = '''
/// A remote action's failure. A remote action throws it to refuse
/// (`throw RemoteError('invalidEmail')`: nothing it emitted is kept); the
/// local action that called it gets it back from `remote.<name>()` (which
/// returns it, null when done), with that [code], `offline` when the
/// backend can't be reached, or `failed` when the action crashed.
class RemoteError {
  RemoteError(this.code);

  final String code;

  @override
  String toString() => 'RemoteError(' + code + ')';
}
''';

/// `StateDelta`: the State fields an action changes. Every field is
/// optional; only the ones set are sent, and the engine merges them over the
/// current state (top-level fields, whole values).
void _writeDelta(StringBuffer out, ClassModel state, Map<String, Model> models) {
  final fields = state.fields.entries.toList();
  out
    ..writeln('/// The State fields an action changes. Pass it to `emit`; unset')
    ..writeln('/// fields keep their current value.')
    ..writeln('class StateDelta {');
  if (fields.isEmpty) {
    out.writeln('  StateDelta();');
  } else {
    out.writeln('  StateDelta({');
    for (final f in fields) {
      out.writeln('    this.${f.key},');
    }
    out.writeln('  });');
  }
  out.writeln();
  for (final f in fields) {
    out.writeln('  ${_nullable(dartType(f.value, models))} ${f.key};');
  }
  if (fields.isNotEmpty) out.writeln();
  out
    ..writeln('  Map<String, dynamic> toJson() {')
    ..writeln('    final json = <String, dynamic>{};');
  for (final f in fields) {
    final type = TypeRef(f.value.name, item: f.value.item, optional: false);
    out.writeln("    if (${f.key} != null) json['${f.key}'] = "
        "${_toJson(type, '${f.key}!', models)};");
  }
  out
    ..writeln('    return json;')
    ..writeln('  }')
    ..writeln('}');
}

  /// Generates `generated/core.dart`: what actions receive as `core`
  /// (`core.api`, `core.navigator`) and the routing/ route names. The
  /// calls go to the engine through `package:metacode/engine/host.dart`.
/// What an app's code reaches of one of its modules: `core.modules.food`.
class ModuleApi {
  final String name;
  final Iterable<String> routes;
  final List<UserFunction> actions;
  final List<UserFunction> values;
  const ModuleApi(this.name,
      {this.routes = const [], this.actions = const [], this.values = const []});

  String get className => '${name[0].toUpperCase()}${name.substring(1)}';
}

/// Dart types that mean the same in every app (a module's models don't
/// exist in the app that embeds it).
final _sharedType =
    RegExp(r'^(String|int|double|num|bool|DateTime)\??$|^List<(String|int|double|num|bool)\??>\??$');

String generateCore(Iterable<String> routes,
    {List<ModuleApi> modules = const []}) {
  final out = StringBuffer(_header)
    ..writeln()
    ..writeln("import 'dart:convert';")
    ..writeln()
    ..writeln("import 'package:metacode/engine/host.dart';")
    ..writeln()
    ..writeln('  /// Route names from routing/, for `core.navigator.push`.')
    ..writeln('class Routes {');
  for (final r in routes) {
    out.writeln("  static const String $r = '$r';");
  }
  out
    ..writeln('}')
    ..write(_coreClasses);
  _writeModules(out, modules);
  return out.toString();
}

/// `AppModules` (`core.modules`): `reset(name)`, and one typed field per
/// module whose methods run its actions and values on its own state and
/// open its routes. Types that only the module knows (its models) are JSON
/// (`Object?`).
void _writeModules(StringBuffer out, List<ModuleApi> modules) {
  String typeOf(String type) => _sharedType.hasMatch(type) ? type : 'Object?';
  out
    ..writeln()
    ..writeln('/// This app\'s modules (modules/<name>/): `core.modules.<name>` runs')
    ..writeln('/// its actions and values (on its own state) and opens its routes.')
    ..writeln('class AppModules {');
  if (modules.isNotEmpty) {
    out
      ..writeln('  AppModules()')
      ..writeln('      : ${modules.map((m) => '${m.name} = ${m.className}Module()').join(',\n        ')};');
    for (final m in modules) {
      out
        ..writeln()
        ..writeln('  /// modules/${m.name}/.')
        ..writeln('  final ${m.className}Module ${m.name};');
    }
    out.writeln();
  }
  out
    ..writeln('  /// Starts the module [name] over: its state (and its own modules\') back')
    ..writeln('  /// to its app.yaml\'s, saved, and its contained routes closed.')
    ..writeln('  Future<void> reset(String name) async {')
    ..writeln("    await hostCall('modules.reset', jsonEncode({'name': name}));")
    ..writeln('  }')
    ..writeln('}');
  for (final m in modules) {
    final c = m.className;
    out
      ..writeln()
      ..writeln('/// Route names of modules/${m.name}/, for `core.modules.${m.name}.navigator.push`.')
      ..writeln('class ${c}Routes {');
    for (final r in m.routes) {
      out.writeln("  static const String $r = '$r';");
    }
    out
      ..writeln('}')
      ..writeln()
      ..writeln('/// Opens modules/${m.name}/\'s routes (over this app).')
      ..writeln('class ${c}Navigator {')
      ..writeln('  /// Opens [route] (use `${c}Routes`). Completes when it closes.')
      ..writeln('  Future<void> push(String route) async {')
      ..writeln("    await hostCall('module.push', jsonEncode({'module': '${m.name}', 'route': route}));")
      ..writeln('  }')
      ..writeln('}')
      ..writeln()
      ..writeln('/// modules/${m.name}/: its actions and values, run on its own state.')
      ..writeln('class ${c}Module {')
      ..writeln('  ${c}Module() : navigator = ${c}Navigator();')
      ..writeln()
      ..writeln('  final ${c}Navigator navigator;')
      ..writeln()
      ..writeln('  /// Starts it over (see `AppModules.reset`).')
      ..writeln('  Future<void> reset() async {')
      ..writeln("    await hostCall('modules.reset', jsonEncode({'name': '${m.name}'}));")
      ..writeln('  }');
    for (final fn in m.actions) {
      final value = fn.params.where((p) => p.name == 'value').firstOrNull;
      out
        ..writeln()
        ..writeln('  /// Runs its action `${fn.name}`.')
        ..writeln('  Future<void> ${fn.name}(${value == null ? '' : '${typeOf(value.type)} value'}) async {')
        ..writeln("    await hostCall('module.action', jsonEncode({'module': '${m.name}', 'name': '${fn.name}'${value == null ? '' : ", 'value': ${_encodeDart(typeOf(value.type), 'value', const {})}"}}));")
        ..writeln('  }');
    }
    for (final fn in m.values) {
      final type = typeOf(fn.returnType);
      out
        ..writeln()
        ..writeln('  /// Its value `${fn.name}`, on its current state.')
        ..writeln('  Future<$type> ${fn.name}() async {')
        ..writeln("    final result = jsonDecode(await hostCall('module.value', jsonEncode({'module': '${m.name}', 'name': '${fn.name}'})));")
        ..writeln('    return ${type == 'Object?' ? 'result' : _decodeDart(type, 'result', const {})};')
        ..writeln('  }');
    }
    out.writeln('}');
  }
}

