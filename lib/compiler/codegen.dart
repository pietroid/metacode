void _writeEnum(StringBuffer out, EnumModel model) {
  final c = model.className;
  out.writeln('enum $c { ${model.values.join(', ')} }');
  out.writeln();
  // dart_eval doesn't support Enum.name / values.byName, so convert explicitly.
  out.writeln('$c \$${model.name}FromJson(String value) {');
  for (final v in model.values.take(model.values.length - 1)) {
    out.writeln("  if (value == '$v') return $c.$v;");
  }
  out.writeln('  return $c.${model.values.last};');
  out.writeln('}');
  out.writeln();
  // For an optional field: dart_eval can't unify null and an enum in a
  // `?:`, so an `if` decides.
  out.writeln('$c? \$${model.name}FromJsonOrNull(Object? value) {');
  out.writeln('  if (value == null) return null;');
  out.writeln('  return \$${model.name}FromJson(value as String);');
  out.writeln('}');
  out.writeln();
  out.writeln('String \$${model.name}ToJson($c value) {');
  for (final v in model.values.take(model.values.length - 1)) {
    out.writeln("  if (value == $c.$v) return '$v';");
  }
  out.writeln("  return '${model.values.last}';");
  out.writeln('}');
}

void _writeClass(StringBuffer out, ClassModel model, Map<String, Model> models) {
  final c = model.className;
  final fields = model.fields.entries.toList();

  out.writeln('class $c {');
  if (fields.isEmpty) {
    out.writeln('  $c();');
  } else {
    out.writeln('  $c({');
    for (final f in fields) {
      out.writeln('    ${f.value.optional ? '' : 'required '}this.${f.key},');
    }
    out.writeln('  });');
  }
  out.writeln();
  for (final f in fields) {
    out.writeln('  ${dartType(f.value, models)} ${f.key};');
  }
  if (fields.isNotEmpty) out.writeln();

  // copyWith
  if (fields.isEmpty) {
    out.writeln('  $c copyWith() => $c();');
  } else {
    out.writeln('  $c copyWith({');
    for (final f in fields) {
      out.writeln('    ${_nullable(dartType(f.value, models))} ${f.key},');
    }
    out.writeln('  }) {');
    out.writeln('    return $c(');
    for (final f in fields) {
      out.writeln('      ${f.key}: ${f.key} ?? this.${f.key},');
    }
    out.writeln('    );');
    out.writeln('  }');
  }
  out.writeln();

  // An optional field of this model: dart_eval can't box a class to unify
  // it with null in a `?:` ("Cannot box"), so an `if` decides.
  out.writeln('  static $c? fromJsonOrNull(Object? json) {');
  out.writeln('    if (json == null) return null;');
  out.writeln('    return $c.fromJson(json as Map);');
  out.writeln('  }');
  out.writeln();

  // fromJson
  out.writeln('  static $c fromJson(Map json) {');
  out.writeln('    return $c(');
  for (final f in fields) {
    out.writeln(
        "      ${f.key}: ${_fromJson(f.value, "json['${f.key}']", models)},");
  }
  out.writeln('    );');
  out.writeln('  }');
  out.writeln();

  // toJson
  out.writeln('  Map<String, dynamic> toJson() {');
  out.writeln('    return {');
  for (final f in fields) {
    out.writeln("      '${f.key}': ${_toJson(f.value, f.key, models)},");
  }
  out.writeln('    };');
  out.writeln('  }');
  out.writeln('}');
}

String _nullable(String type) => type.endsWith('?') ? type : '$type?';

String dartType(TypeRef t, Map<String, Model> models) {
  final base = t.isList
      ? 'List<${dartType(t.item!, models)}>'
      : primitives[t.name] ?? models[t.name]!.className;
  return t.optional ? '$base?' : base;
}

String _fromJson(TypeRef t, String expr, Map<String, Model> models) {
  final String inner;
  if (t.isList) {
    final item = _fromJson(t.item!, 'e', models);
    inner = '($expr as List).map((e) => $item).toList()';
  } else {
    inner = switch (t.name) {
      'string' => '$expr as String',
      'boolean' => '$expr as bool',
      'number' => '$expr as num',
      'datetime' => 'DateTime.parse($expr as String)',
      _ => switch (models[t.name]!) {
          EnumModel m => '\$${m.name}FromJson($expr as String)',
          ClassModel m => '${m.className}.fromJson($expr as Map)',
        },
    };
    if (t.optional) {
      final model = models[t.name];
      if (model is ClassModel) return '${model.className}.fromJsonOrNull($expr)';
      if (model is EnumModel) return '\$${model.name}FromJsonOrNull($expr)';
    }
  }
  return t.optional ? '$expr == null ? null : $inner' : inner;
}

String _toJson(TypeRef t, String expr, Map<String, Model> models) {
  final v = t.optional ? '$expr!' : expr;
  final String inner;
  if (t.isList) {
    final item = _toJson(t.item!, 'e', models);
    inner = item == 'e' ? v : '$v.map((e) => $item).toList()';
  } else {
    inner = switch (t.name) {
      'string' || 'boolean' || 'number' => v,
      'datetime' => '$v.toIso8601String()',
      _ => switch (models[t.name]!) {
          EnumModel m => '\$${m.name}ToJson($v)',
          ClassModel _ => '$v.toJson()',
        },
    };
  }
  if (inner == v) return expr;
  return t.optional ? '$expr == null ? null : $inner' : inner;
}

/// Generates `.generated/labels.dart`: app/views/labels/ as typed getters, for
/// values (and actions) that take `Labels labels`. Every language is in it;
/// the engine says which one to show (the device's, or the one picked with
/// `core.locale.set`), and a key a language lacks falls back to
/// [language], the default.
String generateLabels(Map<String, Map<String, String>> labels, String? language) {
  final languages = labels.keys.toList();
  final fallback = language ?? 'en';
  final defaults = labels[language] ?? const <String, String>{};
  final out = StringBuffer(_header)
    ..writeln()
    ..writeln('/// The app\'s text from app/views/labels/, in [locale].')
    ..writeln('class Labels {')
    ..writeln('  Labels([this.locale = ${_dartString(fallback)}]);')
    ..writeln()
    ..writeln('  /// The language shown: one of [locales] (the labels file name,')
    ..writeln('  /// `en`, `pt_br`).')
    ..writeln('  final String locale;')
    ..writeln()
    ..writeln('  /// Every language in app/views/labels/, the default first.')
    ..writeln('  List<String> get locales => <String>[${[
      fallback,
      for (final l in languages)
        if (l != fallback) l,
    ].map(_dartString).join(', ')}];');
  for (final e in defaults.entries) {
    // locale == 'pt_br' ? '...' : locale == 'es' ? '...' : '<default>'
    final branches = [
      for (final l in languages)
        if (l != language && labels[l]!.containsKey(e.key))
          "locale == ${_dartString(l)} ? ${_dartString(labels[l]![e.key]!)} :",
    ];
    out.writeln();
    if (branches.isEmpty) {
      out.writeln('  String get ${e.key} => ${_dartString(e.value)};');
    } else {
      out.writeln('  String get ${e.key} =>');
      for (final b in branches) {
        out.writeln('      $b');
      }
      out.writeln('      ${_dartString(e.value)};');
    }
  }
  out.writeln('}');
  return out.toString();
}

String _dartString(String value) {
  final escaped = value
      .replaceAll(r'\', r'\\')
      .replaceAll("'", r"\'")
      .replaceAll(r'$', r'\$')
      .replaceAll('\n', r'\n');
  return "'$escaped'";
}

/// Generates `.generated/remote.dart`: `Remote`, what local actions take
/// as `remote`: one method per remote action (app/actions/remote/), which
/// runs it on the backend and completes once its changes are in this
/// client's state. A refusal or a failure throws [RemoteError].
String generateRemote(List<UserFunction> remoteActions, Map<String, Model> models) {
  final out = StringBuffer(_header)
    ..writeln()
    ..writeln("import 'dart:convert';")
    ..writeln()
    ..writeln("import 'package:metacode/engine/host.dart';")
    ..writeln()
    ..writeln("import 'state.dart';")
    ..writeln()
    ..writeln('/// The remote actions (app/actions/remote/), run on the backend. Each')
    ..writeln('/// call completes once the backend has run it and its changes are in')
    ..writeln('/// this client\'s state, with null; or with a RemoteError: the code')
    ..writeln('/// the action refused with, `offline` without a connection, `failed`.')
    ..writeln('/// (Returned, not thrown: dart_eval breaks try/catch around an await.)')
    ..writeln('class Remote {');
  for (final fn in remoteActions) {
    final value = fn.params.where((p) => p.name == 'value').firstOrNull;
    final encoded = value == null ? 'null' : _encodeDart(value.type, 'value', models);
    out
      ..writeln('  Future<RemoteError?> ${fn.name}(${value == null ? '' : '${value.type} value'}) async {')
      ..writeln("    final result = jsonDecode(await hostCall('remote.call',")
      ..writeln("        jsonEncode({'name': '${fn.name}', 'value': $encoded})));")
      ..writeln('    if (result == null) return null;')
      ..writeln('    return RemoteError(result as String);')
      ..writeln('  }');
  }
  out.writeln('}');
  return out.toString();
}

/// Generates `.generated/remote_main.dart`: the backend's bridge to the
/// remote actions. `$remote_<name>` returns '' when the action finished; a
/// `RemoteError` it throws comes out of the interpreter, where
/// `MetacodeProgram.remote` reads its code (its emits are then dropped).
String generateRemoteMain(List<UserFunction> remoteActions, List<String> imports,
    Map<String, Model> models) {
  final out = StringBuffer(_header)
    ..writeln('// ignore_for_file: non_constant_identifier_names, prefer_function_declarations_over_variables')
    ..writeln()
    ..writeln("import 'dart:convert';")
    ..writeln()
    ..writeln("import 'package:metacode/engine/host.dart';")
    ..writeln()
    ..writeln("import 'remote_state.dart';");
  for (final i in imports) {
    out.writeln("import '../$i';");
  }
  out.writeln();
  for (final fn in remoteActions) {
    final args = [
      'state',
      for (final p in fn.params)
        p.name == 'emit' ? 'emit' : _decodeDart(p.type, "params['value']", models),
    ];
    out
      ..writeln('Future<String> \$remote_${fn.name}(String stateJson, String paramsJson) async {')
      ..writeln('  final state = State.fromJson(jsonDecode(stateJson) as Map);')
      ..writeln('  final params = jsonDecode(paramsJson) as Map;')
      ..writeln('  final emit = (StateDelta delta) {')
      ..writeln('    hostEmit(jsonEncode(delta.toJson()));')
      ..writeln('  };')
      ..writeln('  await ${fn.name}(${args.join(', ')});')
      ..writeln("  return '';")
      ..writeln('}')
      ..writeln();
  }
  if (remoteActions.isEmpty) out.writeln('void \$remote_none() {}');
  return '${out.toString().trimRight()}\n';
}

/// Generates `generated/main.dart`: the bridge between the engine and the
/// user's functions. The engine speaks JSON; user code only sees typed objects.
///
/// The engine passes the language to show as `_locale` in the params (see
/// `Labels`); [defaultLanguage] is used without one.
String generateMain(
  List<UserFunction> actions,
  List<UserFunction> bindings,
  List<String> imports,
  Map<String, Model> models, {
  String? defaultLanguage,
}) {
  final out = StringBuffer(_header)
    ..writeln('// ignore_for_file: non_constant_identifier_names, prefer_function_declarations_over_variables')
    ..writeln()
    ..writeln("import 'dart:convert';")
    ..writeln()
    ..writeln("import 'package:metacode/engine/host.dart';")
    ..writeln();
  if (actions.any((fn) => fn.params.any((p) => p.name == 'core'))) {
    out.writeln("import 'core.dart';");
  }
  if (actions.any((fn) => fn.params.any((p) => p.name == 'remote'))) {
    out.writeln("import 'remote.dart';");
  }
  if ([...actions, ...bindings]
      .any((fn) => fn.params.any((p) => p.name == 'labels'))) {
    out.writeln("import 'labels.dart';");
  }
  out.writeln("import 'state.dart';");
  for (final i in imports) {
    out.writeln("import '../$i';");
  }
  out.writeln();

  String call(UserFunction fn) {
    final args = [
      'state',
      for (final p in fn.params)
        switch (p.name) {
          'emit' => 'emit',
          'core' => 'Core()',
          'remote' => 'Remote()',
          'labels' =>
            "Labels((params['_locale'] ?? '${defaultLanguage ?? 'en'}') as String)",
          _ => "params['${p.name}'] as ${p.type}",
        },
    ];
    return '${fn.name}(${args.join(', ')})';
  }

  String paramsLine(UserFunction fn) =>
      fn.params.any((p) =>
              contextParamTypes.containsKey(p.name) || p.name == 'labels')
          ? '  final params = jsonDecode(paramsJson) as Map;\n'
          : '';

  for (final fn in actions) {
    out
      ..writeln('Future<String> \$action_${fn.name}(String stateJson, String paramsJson) async {')
      ..writeln('  final state = State.fromJson(jsonDecode(stateJson) as Map);')
      ..write(paramsLine(fn));
    if (fn.params.any((p) => p.name == 'emit')) {
      out
        ..writeln('  final emit = (StateDelta delta) {')
        ..writeln('    hostEmit(jsonEncode(delta.toJson()));')
        ..writeln('  };');
    }
    out
      ..writeln('  await ${call(fn)};')
      ..writeln("  return '';")
      ..writeln('}')
      ..writeln();
  }

  for (final fn in bindings) {
    out
      ..writeln('String \$binding_${fn.name}(String stateJson, String paramsJson) {')
      ..writeln('  final state = State.fromJson(jsonDecode(stateJson) as Map);')
      ..write(paramsLine(fn))
      ..writeln('  final result = ${call(fn)};')
      ..writeln('  return jsonEncode(${_encodeDart(fn.returnType, 'result', models)});')
      ..writeln('}')
      ..writeln();
  }
  return '${out.toString().trimRight()}\n';
}

/// JSON-encodes a value of a Dart type returned by a binding.
String _encodeDart(String type, String expr, Map<String, Model> models) {
  var t = type.trim();
  final optional = t.endsWith('?');
  if (optional) t = t.substring(0, t.length - 1);
  final v = optional ? '$expr!' : expr;

  final String inner;
  final list = RegExp(r'^List<(.+)>$').firstMatch(t);
  if (list != null) {
    final item = _encodeDart(list.group(1)!, 'e', models);
    inner = item == 'e' ? v : '$v.map((e) => $item).toList()';
  } else if (t == 'DateTime') {
    inner = '$v.toIso8601String()';
  } else {
    final model = models.values.where((m) => m.className == t).firstOrNull;
    inner = switch (model) {
      EnumModel m => '\$${m.name}ToJson($v)',
      ClassModel _ => '$v.toJson()',
      null => v,
    };
  }
  if (inner == v) return expr;
  return optional ? '$expr == null ? null : $inner' : inner;
}

/// Generates `generated/test_app.dart`: typed wrappers that run each action
/// and binding through the compiled program (dart_eval), exactly like the
/// engine. Used by the app's test/. [appPath] is the app folder relative to
/// the repo root (`examples/my_own_app`, `examples/my_own_app/modules/food`), where tests run from.
///
/// Remote calls run in-process against the remote actions' program
/// (`.generated/remote_program.evc`), over the state's `remote` and `shared`
/// fields and [TestApp.system] (seeded from app.yaml), as the engine does
/// without a backend. [scopes] is each state field's scope; [scoped]
/// whether app.yaml's `state:` is split by scope.
String generateTestApp(
  List<UserFunction> actions,
  List<UserFunction> bindings,
  Map<String, Model> models,
  String appPath, {
  List<UserFunction> remoteActions = const [],
  Map<String, String> scopes = const {},
  bool scoped = false,
}) {
  String set(Iterable<String> names) =>
      '<String>{${names.map((n) => "'$n'").join(', ')}}';
  final remoteFields = [
    for (final e in scopes.entries)
      if (e.value == 'remote' || e.value == 'shared') e.key,
  ];
  final out = StringBuffer(_header)
    ..writeln()
    ..writeln("import 'dart:convert';")
    ..writeln("import 'dart:io';")
    ..writeln("import 'dart:typed_data';")
    ..writeln()
    ..writeln("import 'package:fake_async/fake_async.dart';")
    ..writeln("import 'package:metacode/engine/host_plugin.dart';")
    ..writeln("import 'package:metacode/engine/program.dart';")
    ..writeln("import 'package:yaml/yaml.dart';")
    ..writeln()
    ..writeln("import 'core.dart';")
    ..writeln("import 'state.dart';")
    ..writeln()
    ..write(_testAppHead.replaceAll(r'$appPath', appPath))
  ..writeln('  /// The `remote` and `shared` fields, sent to remote actions.')
  ..writeln('  static const _remoteFields = ${set(remoteFields)};')
  ..writeln()
  ..writeln('  /// app.yaml\'s `state:` (JSON), every scope.')
  ..writeln('  static Map<String, dynamic> get _seed {')
  ..writeln("    final doc = loadYaml(File('$appPath/app.yaml').readAsStringSync()) as Map;")
  ..writeln("    return Map<String, dynamic>.from(jsonDecode(jsonEncode(doc['state'] ?? {})) as Map);")
  ..writeln('  }')
  ..writeln()
  ..writeln('  /// The backend\'s `system` fields, which remote calls read and change;')
  ..writeln('  /// app.yaml\'s seeds at first. Set it to start a test from others.')
  ..writeln(scoped
      ? "  Map<String, dynamic> system = Map<String, dynamic>.from((_seed['system'] as Map?) ?? {});"
      : '  Map<String, dynamic> system = {};')
  ..writeln()
  ..writeln('  /// The initial state from $appPath/app.yaml (no `system` fields).')
  ..writeln('  State get initialState {')
  ..writeln('    final seed = _seed;')
  ..writeln(scoped
      ? "    final state = <String, dynamic>{for (final scope in const ['ephemeral', 'local', 'remote', 'shared']) ...?(seed[scope] as Map?)?.cast<String, dynamic>()};"
      : '    final state = seed;')
  ..writeln('    return State.fromJson(state);')
  ..writeln('  }');

  String signature(UserFunction fn) => [
        'State state',
        for (final p in fn.params)
          if (contextParamTypes.containsKey(p.name)) '${p.type} ${p.name}',
      ].join(', ');
  String params(UserFunction fn) {
    final context =
        fn.params.where((p) => contextParamTypes.containsKey(p.name));
    return ", {'_locale': ?locale${context.map((p) => ", '${p.name}': ${p.name}").join()}}";
  }

  for (final fn in actions) {
    final contextOnly =
        fn.params.where((p) => contextParamTypes.containsKey(p.name)).toList();
    final sig = ['State state', for (final p in contextOnly) '${p.type} ${p.name}'].join(', ');
    final args = contextOnly.isEmpty
        ? ''
        : ', {${contextOnly.map((p) => "'${p.name}': ${p.name}").join(', ')}}';
    out
      ..writeln()
      ..writeln('  /// Runs `${fn.name}` and returns the state with its deltas applied.')
      ..writeln('  Future<State> ${fn.name}($sig) =>')
      ..writeln("      _run('${fn.name}', state$args);");
  }
  for (final fn in bindings) {
    final raw = "_program.binding('${fn.name}', state.toJson()${params(fn)})";
    out
      ..writeln()
      ..writeln('  ${fn.returnType} ${fn.name}(${signature(fn)}) {')
      ..writeln('    final result = $raw;')
      ..writeln('    return ${_decodeDart(fn.returnType, 'result', models)};')
      ..writeln('  }');
  }
  out
    ..writeln('}')
    ..write(_collectClass);
  return out.toString();
}

const _collectClass = r'''

/// Collects a remote action's deltas (kept only if it doesn't refuse).
class _Collect implements MetacodeHost {
  final deltas = <Map<String, dynamic>>[];

  @override
  void emit(Map<String, dynamic> delta) => deltas.add(delta);

  @override
  Future<Object?> call(String op, Map<String, dynamic> args) async => null;
}
''';

const _testAppHead = r'''
  /// Runs actions and bindings through the compiled program, like the engine
  /// does, with typed inputs and outputs. Actions run against a fake host:
  /// deltas are applied to the returned state, navigator calls are recorded
  /// in [navigation] and api requests are answered by [api].
  class TestApp implements MetacodeHost {
    late final MetacodeProgram _program = MetacodeProgram(
      ByteData.sublistView(File('$appPath/.generated/program.evc').readAsBytesSync()),
      jsonDecode(File('$appPath/.generated/manifest.json').readAsStringSync())
          as Map<String, dynamic>,
    )..host = this;

  /// Answers `core.api` requests. Defaults to 404.
  ApiResponse Function(String method, String url, Object? body) api =
      (method, url, body) => ApiResponse(status: 404, body: '');

  /// Every delta the last action emitted, in order (as JSON).
  final emitted = <Map<String, dynamic>>[];

  /// Remote actions the last action called (`remote.<name>()`), by name.
  final remoteCalls = <String>[];

  /// When set, `remote.<name>()` throws `RemoteError(offline)` without
  /// running the remote action: the backend can't be reached.
  bool offline = false;

  late final MetacodeProgram _remoteProgram = MetacodeProgram(
    ByteData.sublistView(File('$appPath/.generated/remote_program.evc').readAsBytesSync()),
    {'actions': [], 'bindings': [], 'remote': jsonDecode(File('$appPath/.generated/manifest.json').readAsStringSync())['remote']},
  );

  /// Navigator calls of the last action: `push <route>`, `pop`.
  final navigation = <String>[];

  /// Api requests of the last action: `GET <url>`, `POST <url>`.
  final requests = <String>[];

  /// Modules the last action reset (`core.modules.reset`), by name.
  final modulesReset = <String>[];

  /// Module actions the last action ran (`core.modules.food.addItem(..)`):
  /// `food.addItem` (and ` <value JSON>` when it took one).
  final moduleCalls = <String>[];

  /// What `core.modules.<module>.<value>()` returns, as JSON, by
  /// `module.value` (`food.total`). Unset ones return null.
  final moduleValues = <String, Object?>{};

  /// The language labels are in (a labels file name, `pt_br`); null is the
  /// default one. `core.locale.set` changes it.
  String? locale;

  /// The theme `core.theme.set` picked (`light`, `dark`); null is the style's.
  String? theme;

  Map<String, dynamic> _state = {};

  Future<State> _run(String name, State state,
      [Map<String, dynamic> params = const {}]) async {
    emitted.clear();
    remoteCalls.clear();
    navigation.clear();
    requests.clear();
    modulesReset.clear();
    moduleCalls.clear();
    _state = jsonDecode(jsonEncode(state.toJson())) as Map<String, dynamic>;
    params = {...params, '_locale': ?locale};
    // Fake time: delays inside actions (animations, demo steps) resolve
    // instantly, so tests do not wait in real time.
    var done = false;
    Object? error;
    StackTrace? trace;
    FakeAsync().run((time) {
      _program.action(name, _state, params).then(
          (_) => done = true,
          onError: (Object e, StackTrace s) {
            error = e;
            trace = s;
            done = true;
          });
      while (!done) {
        time.flushMicrotasks();
        if (done) break;
        if (time.pendingTimers.isEmpty) {
          throw StateError('$name never completed (awaits something outside fake time)');
        }
        time.elapse(time.pendingTimers
            .map((t) => t.duration)
            .reduce((a, b) => a < b ? a : b));
      }
    });
    if (error != null) Error.throwWithStackTrace(error!, trace!);
    return State.fromJson(_state);
  }

  @override
  void emit(Map<String, dynamic> delta) {
    emitted.add(delta);
    _state = {..._state, ...delta};
  }

  @override
  Future<Object?> call(String op, Map<String, dynamic> args) async {
    switch (op) {
      case 'api':
        requests.add('${args['method']} ${args['url']}');
        final r = api(args['method'] as String, args['url'] as String, args['body']);
        return {'status': r.status, 'body': r.body};
      case 'navigator.push':
        navigation.add('push ${args['route']}');
      case 'navigator.pop':
        navigation.add('pop');
      case 'locale.set':
        locale = args['locale'] as String?;
      case 'theme.set':
        theme = args['theme'] as String?;
      case 'modules.reset':
        modulesReset.add(args['name'] as String);
      case 'module.action':
        moduleCalls.add('${args['module']}.${args['name']}'
            '${args.containsKey('value') ? ' ${jsonEncode(args['value'])}' : ''}');
      case 'module.value':
        return moduleValues['${args['module']}.${args['name']}'];
      case 'module.push':
        navigation.add('push ${args['module']}.${args['route']}');
      case 'remote.call':
        return _remoteCall(args['name'] as String, args['value']);
    }
    return null;
  }

  /// Runs a remote action in-process: over this state's `remote` and
  /// `shared` fields and [system]. Its `system` changes go to [system], the
  /// rest to the state (as if the backend sent them back).
  Future<String?> _remoteCall(String name, Object? value) async {
    remoteCalls.add(name);
    if (offline) return 'offline';
    final deltas = _Collect();
    _remoteProgram.host = deltas;
    final error = await _remoteProgram.remote(name, {
      for (final e in _state.entries)
        if (_remoteFields.contains(e.key)) e.key: e.value,
      ...system,
    }, {'value': value});
    if (error.isNotEmpty) return error;
    for (final delta in deltas.deltas) {
      final toClient = <String, dynamic>{};
      for (final e in delta.entries) {
        if (system.containsKey(e.key)) {
          system = {...system, e.key: e.value};
        } else {
          toClient[e.key] = e.value;
        }
      }
      if (toClient.isNotEmpty) emit(toClient);
    }
    return null;
  }

''';

/// Decodes a JSON value back into the Dart type a binding returned.
String _decodeDart(String type, String expr, Map<String, Model> models) {
  var t = type.trim();
  final optional = t.endsWith('?');
  if (optional) t = t.substring(0, t.length - 1);

  final String inner;
  final list = RegExp(r'^List<(.+)>$').firstMatch(t);
  if (list != null) {
    inner = '($expr as List).map((e) => ${_decodeDart(list.group(1)!, 'e', models)}).toList()';
  } else {
    final model = models.values.where((m) => m.className == t).firstOrNull;
    inner = switch ((t, model)) {
      ('DateTime', _) => 'DateTime.parse($expr as String)',
      ('int', _) => '($expr as num).toInt()',
      ('double', _) => '($expr as num).toDouble()',
      (_, EnumModel m) => '\$${m.name}FromJson($expr as String)',
      (_, ClassModel m) => '${m.className}.fromJson($expr as Map)',
      _ => '$expr as $t',
    };
  }
  return optional ? '$expr == null ? null : $inner' : inner;
}
