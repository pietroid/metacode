// Validates and compiles a project held in [ProjectFiles], in memory: what
// `dart run tool/metacode.dart` does, and what the app does on every change
// to its files (lib/engine/live_project.dart). No dart:io, so it also runs
// on the web.
//
// Per app: models (including the reserved state.yaml) -> app.yaml state ->
// actions and values (signatures) -> labels -> pages and components (and
// `module:` names against modules/) -> navigation (optional) -> style
// (optional). Then, per app: .generated/state.dart (+ StateDelta),
// .generated/core.dart (Core, Routes), .generated/labels.dart,
// .generated/main.dart, compiled .generated/program.evc + manifest.json, and
// .generated/test_app.dart (typed test harness) and .generated/INDEX.md (the
// app's map). The root also gets .generated/bundle.json (the whole app tree,
// which the engine runs), .generated/files.json (the project's text files:
// the web's default project), .generated/all_test.dart and
// .generated/layout_states.json (every app's tests/ states, for
// tool/layout_test.dart).

