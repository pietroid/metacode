/// The outcome of [build].
class BuildResult {
  final Issues issues;
  final AppProject root;

  /// The engine's input (`.generated/bundle.json`), null when invalid.
  final String? bundle;

  /// Files to write, by path within the project: String or Uint8List.
  final Map<String, Object> outputs;

  BuildResult(this.issues, this.root, this.bundle, this.outputs);

  /// Writes [outputs] into [files]; unchanged ones are not rewritten (so
  /// whatever watches them does not reload).
  Future<void> writeTo(ProjectFiles files) async {
    for (final MapEntry(key: path, value: contents) in outputs.entries) {
      if (contents is String) {
        await files.write(path, contents);
      } else {
        await files.writeBytes(path, contents as Uint8List);
      }
    }
  }
}

/// Validates [files] (the root app's folder, at [path] in the repo) and,
/// unless [checkOnly], generates everything.
BuildResult build(ProjectFiles files,
    {String path = 'examples/my_own_app', bool checkOnly = false}) {
  final issues = Issues();
  final root = loadApp(files, path, issues);
  final outputs = <String, Object>{};
  String? bundle;
  if (!issues.hasErrors && !checkOnly) {
    final node = _generate(root, issues, outputs);
    if (node != null && !issues.hasErrors) {
      bundle = jsonEncode(node);
      outputs['.generated/bundle.json'] = bundle;
      outputs['.generated/files.json'] = jsonEncode(files.toSnapshot());
      outputs['.generated/all_test.dart'] = _allTests(files, path);
    }
  }
  return BuildResult(issues, root, bundle, outputs);
}

/// One test entrypoint for the whole tree, so `flutter test` compiles and
/// starts once instead of once per file. It imports every user .dart file
/// (so each one is type-checked) and runs each file's `main()` in a group.
String _allTests(ProjectFiles files, String path) {
  final dartFiles = [
    for (final p in files.paths)
      if (p.endsWith('.dart') && ProjectFiles.isSource(p)) p,
  ];
  final hasMain = RegExp(r'^void main\(', multiLine: true);
  final out = StringBuffer('// GENERATED by `dart run tool/metacode.dart`. Do not edit.\n')
    ..writeln('// Runs every test in the tree: flutter test $path/.generated/all_test.dart')
    ..writeln('// ignore_for_file: unused_import')
    ..writeln()
    ..writeln("import 'package:flutter_test/flutter_test.dart';")
    ..writeln();
  final tests = <String>[];
  for (final (i, f) in dartFiles.indexed) {
    out.writeln("import '../$f' as f$i;");
    if (hasMain.hasMatch(files.read(f)!)) {
      tests.add("  group('$f', f$i.main);");
    }
  }
  out
    ..writeln()
    ..writeln('void main() {')
    ..writeAll(tests, '\n')
    ..writeln()
    ..writeln('}');
  return out.toString();
}

/// Generates [app] and its modules into [outputs]; returns its bundle node
/// (null if compiling failed).
Map<String, dynamic>? _generate(
    AppProject app, Issues issues, Map<String, Object> outputs) {
  final modules = <String, dynamic>{};
  for (final child in app.modules.values) {
    final node = _generate(child, issues, outputs);
    if (node == null) return null;
    modules[child.name] = node;
  }

  final userFiles = {
    for (final fn in [...app.actions, ...app.bindings]) fn.file,
  }.toList()
    ..sort();

  final generated = {
    '.generated/state.dart': generateState(app.models),
    '.generated/core.dart': generateCore(app.navigation.routes.keys),
    '.generated/labels.dart':
        generateLabels(app.defaultLabels, app.defaultLanguage),
    '.generated/main.dart':
        generateMain(app.actions, app.bindings, userFiles, app.models),
    '.generated/test_app.dart':
        generateTestApp(app.actions, app.bindings, app.models, app.path),
    // The app's map for agents and people; not part of the bundle.
    '.generated/INDEX.md': generateIndex(app),
  };
  generated.forEach((file, code) => outputs[app.at(file)] = code);

  // The engine runs one bundled library per app. dart_eval mis-resolves some
  // calls across libraries (e.g. an action calling a value), so user files
  // stay separate for editing and are merged here for execution.
  final source = _bundle([
    generated['.generated/state.dart']!,
    generated['.generated/core.dart']!,
    generated['.generated/labels.dart']!,
    for (final folder in ['app/actions', 'app/views/values'])
      for (final f in app.files.list(app.at(folder), recursive: true))
        if (isUserCode(f)) stripTests(app.files.read(f)!),
    generated['.generated/main.dart']!,
  ]);
  // (test_app.dart runs on the host, not in the interpreter.)

  final Uint8List bytecode;
  try {
    final program = (Compiler()..addPlugin(const HostPlugin())).compile({
      'metacode': {'main.dart': source},
    });
    bytecode = program.write();
  } catch (e) {
    issues.scoped(app.prefix).error('actions/values', '',
        'could not compile for the engine (dart_eval): $e');
    return null;
  }
  outputs[app.at('.generated/program.evc')] = bytecode;

  final manifest = {
    'actions': [for (final f in app.actions) f.name],
    'bindings': [for (final f in app.bindings) f.name],
  };
  outputs[app.at('.generated/manifest.json')] =
      '${const JsonEncoder.withIndent('  ').convert(manifest)}\n';

  return {
    'name': app.title,
    'description': app.description,
    'ui': {'widgets': app.widgets},
    'state': app.state,
    'navigation': app.navigationDoc,
    'labels': app.labels,
    'language': app.defaultLanguage,
    'style': app.styleDoc,
    'manifest': manifest,
    'program': base64Encode(bytecode),
    'modules': modules,
  };
}

/// Merges Dart sources into one library: relative imports are dropped (all
/// code ends up in the same file); `dart:` imports and the engine host
/// bridge (see lib/engine/host.dart) are kept once.
String _bundle(List<String> sources) {
  final imports = <String>{"import 'dart:convert';"};
  final bodies = <String>[];
  for (final source in sources) {
    final body = <String>[];
    for (final line in source.split('\n')) {
      final trimmed = line.trim();
      if (trimmed.startsWith('import ')) {
        if (trimmed.contains("'dart:") ||
            trimmed.contains("'${HostPlugin.library}'")) {
          imports.add(trimmed);
        }
        continue;
      }
      body.add(line);
    }
    bodies.add(body.join('\n'));
  }
  return '${imports.join('\n')}\n\n${bodies.join('\n')}';
}
